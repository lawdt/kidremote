namespace KidRemote.Core;

/// <summary>
/// Фразы для экрана блокировки. Показываются вместо напоминания попросить время:
/// закрытый экран — повод заняться чем-то другим, а не ждать у монитора.
/// </summary>
internal static class Motivation
{
    private static readonly string[] Phrases =
    {
        "Время исследовать мир",
        "Ты можешь больше",
        "Самое интересное начинается за дверью",
        "Мир снаружи в максимальном разрешении",
        "Придумай то, чего ещё не было",
        "Построй что-нибудь своими руками",
        "Лучшие идеи приходят на ходу",
        "Нарисуй то, что тебе приснилось",
        "Книга открывается быстрее, чем грузится игра",
        "Позови друга — вживую интереснее",
        "Прокачивай себя, а не персонажа",
        "Настоящие приключения не сохраняются в облаке",
        "Найди сегодня что-нибудь новое",
        "Сделай то, что давно откладывал",
        "Научись чему-нибудь за этот час",
        "Спроси у родителей, как это устроено",
        "Собери что-нибудь из того, что лежит без дела",
        "Выйди на улицу — там уже всё началось",
        "Телу тоже нужен апгрейд",
        "Придумай свою игру",
        "Хорошая мысль приходит в тишине",
        "Посмотри на небо, оно каждый день другое",
        "Сделай подарок своими руками",
        "Расскажи кому-нибудь историю",
        "Разбери завал на столе — найдёшь забытое сокровище",
        "Попробуй то, что раньше не получалось"
    };

    private static int _lastIndex = -1;

    /// <summary>Случайная фраза, но не та же самая, что была перед этим.</summary>
    public static string Next()
    {
        if (Phrases.Length == 1) return Phrases[0];

        int index;
        do
        {
            index = Random.Shared.Next(Phrases.Length);
        }
        while (index == _lastIndex);

        _lastIndex = index;
        return Phrases[index];
    }
}
